"""
Prepare Seizure Detection Dataset for YOLOv8 Training
Converts unusual_movement frames to YOLO format

Usage:
    python scripts/prepare_seizure_yolo_dataset.py

Output:
    - datasets/vision/yolo_seizure/train/images/
    - datasets/vision/yolo_seizure/train/labels/
    - datasets/vision/yolo_seizure/val/
    - datasets/vision/yolo_seizure/test/
    - datasets/vision/yolo_seizure/dataset.yaml
"""

import os
import json
import shutil
from pathlib import Path

try:
    from tqdm import tqdm
except ImportError:
    tqdm = lambda x, **kwargs: x


def prepare_seizure_yolo_dataset():
    """Prepare YOLO dataset from processed seizure frames"""
    
    print("\n" + "="*70)
    print("PREPARING SEIZURE DETECTION YOLO DATASET")
    print("="*70)
    
    # Paths
    base_dir = 'datasets/vision/processed/unusual_movement'
    splits_file = os.path.join(base_dir, 'splits.json')
    frames_dir = os.path.join(base_dir, 'frames')
    output_root = 'datasets/vision/yolo_seizure'
    
    # Check inputs
    if not os.path.exists(splits_file):
        print(f"\n[X] ERROR: Splits file not found: {splits_file}")
        print("[!] Run: python scripts/preprocess_unusual_movement.py --extract-frames --create-splits")
        return
    
    if not os.path.exists(frames_dir):
        print(f"\n[X] ERROR: Frames not extracted: {frames_dir}")
        print("[!] Run: python scripts/preprocess_unusual_movement.py --extract-frames")
        return
    
    print(f"\n[*] Loading splits from: {splits_file}")
    with open(splits_file, 'r') as f:
        splits = json.load(f)
    
    # Create output directories
    print("\n[*] Creating YOLO directory structure...")
    for split in ['train', 'val', 'test']:
        os.makedirs(os.path.join(output_root, split, 'images'), exist_ok=True)
        os.makedirs(os.path.join(output_root, split, 'labels'), exist_ok=True)
    print("[OK] Directories created")
    
    # Statistics
    stats = {'train': {'normal': 0, 'seizure': 0},
             'val': {'normal': 0, 'seizure': 0},
             'test': {'normal': 0, 'seizure': 0}}
    
    # Process each split
    for split_name in ['train', 'val', 'test']:
        print(f"\n" + "-"*70)
        print(f"[*] Processing {split_name.upper()} split")
        print("-"*70)
        
        normal_videos = splits[split_name]['normal']
        seizure_videos = splits[split_name]['seizure']
        
        print(f"[*] Normal videos: {len(normal_videos)}")
        print(f"[*] Seizure videos: {len(seizure_videos)}")
        
        output_img_dir = os.path.join(output_root, split_name, 'images')
        output_lbl_dir = os.path.join(output_root, split_name, 'labels')
        
        # Process normal frames (class 0)
        print(f"\n[*] Copying normal frames...")
        for video_name in tqdm(normal_videos, desc="  Normal"):
            video_stem = video_name.replace('.mp4', '')
            frame_pattern = os.path.join(frames_dir, 'normal', f"{video_stem}_frame_*.jpg")
            
            for frame_path in Path(frames_dir, 'normal').glob(f"{video_stem}_frame_*.jpg"):
                # Copy image
                shutil.copy2(frame_path, os.path.join(output_img_dir, frame_path.name))
                
                # Create YOLO label (class 0 = normal, full frame)
                label_path = os.path.join(output_lbl_dir, frame_path.name.replace('.jpg', '.txt'))
                with open(label_path, 'w') as f:
                    f.write("0 0.5 0.5 0.8 0.8\n")
                
                stats[split_name]['normal'] += 1
        
        # Process seizure frames (class 1)
        print(f"\n[*] Copying seizure frames...")
        for video_name in tqdm(seizure_videos, desc="  Seizure"):
            video_stem = video_name.replace('.mp4', '')
            
            for frame_path in Path(frames_dir, 'seizure').glob(f"{video_stem}_frame_*.jpg"):
                # Copy image
                shutil.copy2(frame_path, os.path.join(output_img_dir, frame_path.name))
                
                # Create YOLO label (class 1 = seizure, full frame)
                label_path = os.path.join(output_lbl_dir, frame_path.name.replace('.jpg', '.txt'))
                with open(label_path, 'w') as f:
                    f.write("1 0.5 0.5 0.8 0.8\n")
                
                stats[split_name]['seizure'] += 1
        
        print(f"\n[OK] {split_name.upper()} complete:")
        print(f"    Normal frames: {stats[split_name]['normal']:,}")
        print(f"    Seizure frames: {stats[split_name]['seizure']:,}")
    
    # Create dataset.yaml
    print("\n" + "-"*70)
    print("[*] Creating dataset.yaml...")
    
    yaml_content = f"""# Seizure Detection Dataset
# Generated by prepare_seizure_yolo_dataset.py

path: ../datasets/vision/yolo_seizure  # dataset root
train: train/images
val: val/images
test: test/images

# Classes
nc: 2  # number of classes
names: ['normal', 'seizure']  # class names

# Statistics
# Train: {stats['train']['normal'] + stats['train']['seizure']:,} frames ({stats['train']['normal']:,} normal, {stats['train']['seizure']:,} seizure)
# Val:   {stats['val']['normal'] + stats['val']['seizure']:,} frames ({stats['val']['normal']:,} normal, {stats['val']['seizure']:,} seizure)
# Test:  {stats['test']['normal'] + stats['test']['seizure']:,} frames ({stats['test']['normal']:,} normal, {stats['test']['seizure']:,} seizure)
"""
    
    yaml_path = os.path.join(output_root, 'dataset.yaml')
    with open(yaml_path, 'w') as f:
        f.write(yaml_content)
    
    print(f"[OK] Created: {yaml_path}")
    
    # Final summary
    print("\n" + "="*70)
    print("YOLO DATASET PREPARATION COMPLETE")
    print("="*70)
    print(f"\nLocation: {output_root}/\n")
    
    total_train = stats['train']['normal'] + stats['train']['seizure']
    total_val = stats['val']['normal'] + stats['val']['seizure']
    total_test = stats['test']['normal'] + stats['test']['seizure']
    total_all = total_train + total_val + total_test
    
    print(f"Train:  {total_train:,} frames ({stats['train']['normal']:,} normal, {stats['train']['seizure']:,} seizure)")
    print(f"Val:    {total_val:,} frames ({stats['val']['normal']:,} normal, {stats['val']['seizure']:,} seizure)")
    print(f"Test:   {total_test:,} frames ({stats['test']['normal']:,} normal, {stats['test']['seizure']:,} seizure)")
    print(f"\nTotal:  {total_all:,} frames")
    
    print("\n" + "="*70)
    print("NEXT STEPS FOR KAGGLE:")
    print("="*70)
    print("\n1. Compress the dataset:")
    print("   7z a -tzip seizure_dataset.zip datasets/vision/yolo_seizure")
    print("\n2. Upload to Kaggle as new dataset:")
    print("   - Name: 'seizure-detection-yolo'")
    print("   - Files: seizure_dataset.zip")
    print("\n3. Create Kaggle notebook with training code")
    print("   (See: notebooks/train_seizure_detector.py)")
    print("\n4. Train YOLOv8:")
    print("   yolo detect train data=dataset.yaml model=yolov8n.pt epochs=30")
    print("\n" + "="*70 + "\n")


if __name__ == '__main__':
    prepare_seizure_yolo_dataset()

